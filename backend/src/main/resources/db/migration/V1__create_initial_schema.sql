CREATE TABLE dpcs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    account_information VARCHAR(255)
);

CREATE TABLE companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255)
);

CREATE TABLE contacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    phone_number VARCHAR(255),
    company_id BIGINT NOT NULL REFERENCES companies (id)
);

CREATE TABLE call_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dpc_id BIGINT NOT NULL REFERENCES dpcs (id),
    contact_id BIGINT REFERENCES contacts (id),
    phone_number VARCHAR(255) NOT NULL,
    call_timestamp TIMESTAMP WITH TIME ZONE NOT NULL,
    duration_seconds INTEGER NOT NULL,
    verification_status VARCHAR(255) NOT NULL
);

CREATE TABLE outreach_statuses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL UNIQUE REFERENCES companies (id),
    status VARCHAR(255) NOT NULL,
    latest_call_record_id BIGINT REFERENCES call_records (id),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
